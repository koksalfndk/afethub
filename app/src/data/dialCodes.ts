// Türkiye first — it is the operating country, and a list that opens on Afganistan
// makes the common case the slowest one. Everything else is alphabetical in Turkish.
export const DIAL_COUNTRIES: DialCountry[] = [
  RAW[0],
  ...RAW.slice(1).sort((a, b) => a.name.localeCompare(b.name, 'tr')),
];

// Every distinct code, longest first. Used by splitPhone(): +994 must win over +9.
export const DIAL_CODE_LIST: string[] = Array.from(new Set(DIAL_COUNTRIES.map((c) => c.dial)))
  .sort((a, b) => b.length - a.length);

// What the picker shows: "Türkiye +90". The stored value stays the bare code, so an
// existing number does not change meaning when the label does.
export const dialLabel = (c: DialCountry): string => `${c.name} ${c.dial}`;
